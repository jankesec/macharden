#!/usr/bin/env python3
"""Generate docs/CHECKS.md from data/compliance_mappings.json and the lib/audit_*.sh registry.

    generate_checks_doc.py            write docs/CHECKS.md
    generate_checks_doc.py --check    exit 1 when docs/CHECKS.md is out of date
    generate_checks_doc.py --summary  print "<total> <hardening> <network> <secrets> <persistence>"

Standard library only, so CI can run it without installing anything.
"""

import argparse
import glob
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUTPUT = os.path.join(ROOT, "docs", "CHECKS.md")
DOMAINS = (
    ("hardening", "System hardening"),
    ("network", "Network and perimeter"),
    ("secrets", "Secrets, keys and credentials"),
    ("persistence", "Persistence and daemons"),
)
REGISTER = re.compile(r'^\s*register_check\s+"([A-Z]+-[0-9]+)"\s+"([a-z]+)"\s+"([^"]*)"\s+([0-9]+)\s', re.M)


def load_registry():
    """{check id: {category, title, weight}} from the register_check calls in lib/audit_*.sh."""
    checks = {}
    for path in sorted(glob.glob(os.path.join(ROOT, "lib", "audit_*.sh"))):
        with open(path, encoding="utf-8") as handle:
            for check_id, category, title, weight in REGISTER.findall(handle.read()):
                checks[check_id] = {"category": category, "title": title, "weight": int(weight)}
    return checks


def load_mappings():
    with open(os.path.join(ROOT, "data", "compliance_mappings.json"), encoding="utf-8") as handle:
        return json.load(handle)


def tool_version():
    with open(os.path.join(ROOT, "bin", "macharden"), encoding="utf-8") as handle:
        return re.search(r'^MACHAR_VERSION="([^"]+)"', handle.read(), re.M).group(1)


def ids_in_domain(registry, domain):
    return sorted((i for i, c in registry.items() if c["category"] == domain), key=lambda i: int(i.split("-")[1]))


def summary(registry):
    return [len(registry)] + [len(ids_in_domain(registry, domain)) for domain, _ in DOMAINS]


def table_row(check_id, check, mapping):
    code = check_id.replace("-", "&#8209;")  # non-breaking hyphen keeps IDs on one line
    title = check["title"].replace("|", "\\|")
    return (f"| <code>{code}</code> | {title} | CIS {mapping['cis']['id']} | "
            f"{mapping['nist']['primary']} | {mapping['mitre']['primary_technique']} | {check['weight']} |")


def render():
    registry, data = load_registry(), load_mappings()
    mappings = data["mappings"]
    if set(registry) != set(mappings):
        sys.exit("lib/audit_*.sh and data/compliance_mappings.json list different checks: "
                 + ", ".join(sorted(set(registry) ^ set(mappings))))
    frameworks = data["metadata"]["frameworks"]
    counts = summary(registry)
    domain_text = ", ".join(f"{label} ({count})" for (_, label), count in zip(DOMAINS, counts[1:]))
    lines = [
        "# Security checks reference",
        "",
        "<!-- Generated by scripts/generate_checks_doc.py from data/compliance_mappings.json and "
        "lib/audit_*.sh. Do not edit by hand; run `make docs`. -->",
        "",
        f"macharden {tool_version()} runs **{counts[0]} checks** in four domains: {domain_text}.",
        "",
        "Every check carries one primary identifier per framework:",
        "",
        f"- **CIS**: {frameworks['cis']['name']} (mappings written against {frameworks['cis']['standard']})",
        f"- **NIST**: {frameworks['nist']['name']} control",
        f"- **MITRE**: ATT&CK technique, {frameworks['mitre']['standard']}",
        "",
        "The **weight** (1-10) is the check's share of the Hardening Index; "
        "[ARCHITECTURE.md](ARCHITECTURE.md) describes the scoring model. The complete mapping, "
        "including secondary identifiers and reference links, is in "
        "[`data/compliance_mappings.json`](../data/compliance_mappings.json).",
    ]
    for domain, label in DOMAINS:
        ids = ids_in_domain(registry, domain)
        lines += ["", f"## {label} (`{domain}`, {len(ids)} checks)", "",
                  "| Check | Control | CIS Benchmark | NIST 800-53 | MITRE ATT&CK | Weight |",
                  "|:---|:---|:---:|:---:|:---:|:---:|"]
        lines += [table_row(i, registry[i], mappings[i]) for i in ids]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail when docs/CHECKS.md is out of date")
    parser.add_argument("--summary", action="store_true", help="print the check counts and exit")
    args = parser.parse_args()
    if args.summary:
        print(" ".join(str(n) for n in summary(load_registry())))
        return 0
    text = render()
    if args.check:
        current = open(OUTPUT, encoding="utf-8").read() if os.path.isfile(OUTPUT) else ""
        if current != text:
            print("docs/CHECKS.md is out of date; run 'make docs'", file=sys.stderr)
            return 1
        return 0
    with open(OUTPUT, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    print(f"wrote {os.path.relpath(OUTPUT, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
